/**
 * Helper to find Barangay Purok Data by ID or Name
 */
export function getBarangayPurokData(sectorOrBarangayName: string): BarangayPurokData | undefined {
  if (!sectorOrBarangayName) return undefined;
  const clean = sectorOrBarangayName.trim().toLowerCase();

  return DINGALAN_BARANGAYS_PUROK_DATA.find((b) => {
    return (
      b.id.toLowerCase() === clean ||
      b.barangayName.toLowerCase() === clean ||
      clean.includes(b.barangayName.toLowerCase()) ||
      b.barangayName.toLowerCase().includes(clean) ||
      (clean === 'dingalan' && b.id === 'poblacion') ||
      (clean === 'bay' && b.id === 'paltic') ||
      (clean === 'cabog' && b.id === 'cabischasan')
    );
  });
}
